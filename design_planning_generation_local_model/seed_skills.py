def main():
    if "--list" in sys.argv:
        skills = skill_library.list_skills()
        print(f"当前技能库: {len(skills)} 条")
        for s in skills:
            mark = "★预置" if str(s.get("description", "")).startswith("【系统预置】") else "  用户"
            print(f"  {mark}  {s.get('name')}  (updated {s.get('updated_at')})")
        return

    existing = {s.get("name") for s in skill_library.list_skills()}
    created, skipped = [], []
    for card in SEED_SKILLS:
        if card["name"] in existing:
            skipped.append(card["name"])
            continue
        skill_library.create_skill(
            name=card["name"],
            content=card["content"],
            description=card["description"],
        )
        created.append(card["name"])

    print("预置技能卡种子写入完成（方案模块五）")
    for n in created:
        print(f"  [新增] {n}")
    for n in skipped:
        print(f"  [跳过] {n}（同名已存在，用户治理优先）")
    print(f"共 {len(created)} 新增 / {len(skipped)} 跳过；合计 {len(skill_library.list_skills())} 条")


if __name__ == "__main__":
    main()
